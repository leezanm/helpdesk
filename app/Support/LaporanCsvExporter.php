<?php

namespace App\Support;

use App\Models\Report;
use Illuminate\Database\Eloquent\Builder;
use Symfony\Component\HttpFoundation\StreamedResponse;

/**
 * CSV export for Laporan_Keseluruhan ("Eksport CSV" on the laporan page).
 *
 * Spec: .kiro/specs/laporan-keseluruhan-ui-refresh (task 11.1,
 * Requirement 11 criteria 5 to 8, 10, 18 and 19).
 *
 * The export is the one approved piece of new server code in an otherwise
 * UI-only specification. It is deliberately built from Laravel and PHP
 * built-ins only — response()->streamDownload() plus fputcsv() — so no
 * composer or npm entry is added (Requirement 11 criterion 19).
 *
 * This class only writes: the caller (ReportAll::exportCsv()) owns the
 * authorisation check, the empty-result message and the file name, and hands
 * in a query that is already filtered and ordered. Keeping the filtering in
 * the component means the export and the Jadual_Aduan table read the exact
 * same query (ReportAll::listQuery()), so a row in the file can never
 * disagree with a row on screen.
 */
final class LaporanCsvExporter
{
    /**
     * The nine Jadual_Aduan data columns, in table order. "Tindakan" is left
     * out because it is a button, not data (Requirement 11 criterion 5).
     */
    public const HEADERS = ['Bil.', 'Tiket', 'Subjek', 'Bahagian', 'Kategori', 'Risiko', 'Tarikh', 'Status', 'Rating'];

    /** Rows held in memory at a time while streaming (Requirement 11 criterion 18). */
    public const CHUNK_SIZE = 500;

    /** Placeholder for an empty cell (Requirement 11 criterion 7). */
    private const BLANK = '-';

    /**
     * Stream a UTF-8 CSV (with BOM) for the given query.
     *
     * The query must already be filtered AND totally ordered by the caller:
     * chunk() pages with offset/limit, so without a tie breaker on a
     * non-unique sort column it can skip or repeat rows. ReportAll::listQuery()
     * supplies that tie breaker (orderByDesc('id')) — do not re-order here.
     *
     * @param  Builder<Report>  $query
     */
    public static function stream(Builder $query, string $filename): StreamedResponse
    {
        return response()->streamDownload(function () use ($query) {
            $out = fopen('php://output', 'w');

            // UTF-8 BOM so spreadsheet applications detect the encoding and
            // Malay characters are not mangled on open.
            fwrite($out, "\xEF\xBB\xBF");

            self::write($out, self::HEADERS);

            // Running counter across chunks: Bil. is 1..n for the whole result
            // set, not per page (Requirement 11 criterion 6).
            $bil = 0;

            $query->chunk(self::CHUNK_SIZE, function ($reports) use ($out, &$bil) {
                foreach ($reports as $report) {
                    self::write($out, self::row($report, ++$bil));
                }

                // Push what has been written so far to the client and let the
                // chunk's models go out of scope, so a large result set never
                // sits in memory as one collection.
                flush();
            });

            fclose($out);
        }, $filename, [
            // Requirement 11 criterion 10. Content-Disposition: attachment is
            // generated by streamDownload() from $filename.
            'Content-Type' => 'text/csv; charset=UTF-8',
        ]);
    }

    /**
     * One CSV data row for one aduan.
     *
     * Deliberate differences from the on-screen table: Subjek is the full text
     * (the table truncates it with Str::limit() for layout reasons only),
     * Risiko is the full riskLevel label instead of the badge, and Rating is
     * the raw 1..5 integer instead of star icons — a spreadsheet needs values
     * it can filter and total (Requirement 11 criterion 6).
     *
     * @return array<int, int|string>
     */
    public static function row(Report $report, int $bil): array
    {
        return [
            $bil,
            self::text($report->ticket_no),
            self::text($report->subject),
            self::text($report->bahagian_pengadu),
            self::text($report->category?->desc),
            self::text($report->riskLevel?->label),
            self::text(convertDateFormat($report->submitted_at, 'LL')),
            self::text($report->status?->desc),
            self::rating($report->rating),
        ];
    }

    /** Write one row with explicit CSV settings (comma, double quote). */
    private static function write($handle, array $row): void
    {
        // The separator and enclosure are required by Requirement 11
        // criterion 8; the empty escape character is plain RFC 4180 CSV, which
        // is what spreadsheet applications parse, and it also pins down the
        // one fputcsv() argument whose default is changing across PHP
        // versions. With these settings a field containing a comma, a double
        // quote or a newline round-trips through str_getcsv() unchanged.
        fputcsv($handle, $row, ',', '"', '');
    }

    /** A text cell, or the dash placeholder when the value is empty. */
    private static function text(?string $value): string
    {
        $value = trim((string) $value);

        return $value === '' ? self::BLANK : $value;
    }

    /**
     * Rating as the raw 1..5 integer. No feedback yet means no rating, and
     * rating 0 is not a value the feedback form can produce, so both are
     * treated as empty.
     */
    private static function rating($value): int|string
    {
        return filled($value) && (int) $value !== 0 ? (int) $value : self::BLANK;
    }
}
